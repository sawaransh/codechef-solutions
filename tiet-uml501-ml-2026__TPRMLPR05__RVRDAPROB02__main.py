import pandas as pd
import numpy as np

from mlxtend.preprocessing import (
    TransactionEncoder
)

from mlxtend.frequent_patterns import (
    apriori,
    fpgrowth,
    association_rules
)


class AssociationRuleMiningAnalysis:
    """
    Perform Association Rule Mining
    using Apriori and FP-Growth.
    """

    def __init__(self):
        """
        Load the dataset from
        market_basket_transactions.csv.
        """
        self.df = pd.read_csv('market_basket_transactions.csv')
        self.basket_df = None
        self.apriori_itemsets = None
        self.fpgrowth_itemsets = None

    def prepare_transactions(self):
        """
        Convert the dataset into transaction baskets
        """
        transactions = (
            self.df.groupby('TransactionID')['Item']
            .apply(list)
            .tolist()
        )
        te = TransactionEncoder()
        te_ary = te.fit(transactions).transform(transactions)
        self.basket_df = pd.DataFrame(te_ary, columns=te.columns_)
        return self.basket_df

    def generate_apriori_itemsets(self, min_support=0.2):
        """
        Generate frequent itemsets using the Apriori algorithm
        """
        if self.basket_df is None:
            self.prepare_transactions()
        self.apriori_itemsets = apriori(
            self.basket_df, min_support=min_support, use_colnames=True
        )
        return self.apriori_itemsets

    def generate_fpgrowth_itemsets(self, min_support=0.2):
        """
        Generate frequent itemsets using the FP-Growth algorithm
        """
        if self.basket_df is None:
            self.prepare_transactions()
        self.fpgrowth_itemsets = fpgrowth(
            self.basket_df, min_support=min_support, use_colnames=True
        )
        return self.fpgrowth_itemsets

    def generate_association_rules(self, min_confidence=0.5):
        """
        Generate association rules containing:
        - Antecedent
        - Consequent
        - Support
        - Confidence
        - Lift
        """
        if self.apriori_itemsets is None:
            self.generate_apriori_itemsets()

        if self.apriori_itemsets.empty:
            return pd.DataFrame(
                columns=['antecedents', 'consequents', 'support', 'confidence', 'lift']
            )

        rules = association_rules(
            self.apriori_itemsets, metric="confidence", min_threshold=min_confidence
        )
        if rules.empty:
            return pd.DataFrame(
                columns=['antecedents', 'consequents', 'support', 'confidence', 'lift']
            )

        return rules[['antecedents', 'consequents', 'support', 'confidence', 'lift']].copy()

    def compare_algorithm_performance(self, min_support=0.2):
        """
        Compare:
        - Number of itemsets generated by Apriori
        - Number of itemsets generated by FP-Growth
        """
        apriori_res = self.generate_apriori_itemsets(min_support=min_support)
        fpgrowth_res = self.generate_fpgrowth_itemsets(min_support=min_support)
        return {
            "apriori_itemsets": len(apriori_res),
            "fpgrowth_itemsets": len(fpgrowth_res)
        }

    def get_dataset(self):
        """
        Return the loaded dataset
        """
        return self.df

    def generate_analysis_summary(self, min_support=0.2):
        """
        Generate a summary containing:
        - Total transactions
        - Total unique items
        - Total Apriori itemsets
        - Total FP-Growth itemsets
        """
        if self.apriori_itemsets is None:
            self.generate_apriori_itemsets(min_support=min_support)
        if self.fpgrowth_itemsets is None:
            self.generate_fpgrowth_itemsets(min_support=min_support)

        return {
            "total_transactions": int(self.df['TransactionID'].nunique()),
            "total_unique_items": int(self.df['Item'].nunique()),
            "total_apriori_itemsets": len(self.apriori_itemsets),
            "total_fpgrowth_itemsets": len(self.fpgrowth_itemsets)
        }


# Do not modify the __main__ block below
if __name__ == "__main__":
    analysis = AssociationRuleMiningAnalysis()
    analysis.prepare_transactions()
    print("Apriori Itemsets:")
    print(analysis.generate_apriori_itemsets())
    print("\nFP-Growth Itemsets:")
    print(analysis.generate_fpgrowth_itemsets())
    print("\nAssociation Rules:")
    print(analysis.generate_association_rules())
    print("\nAlgorithm Performance Comparison:")
    print(analysis.compare_algorithm_performance())
    print("\nAnalysis Summary:")
    print(analysis.generate_analysis_summary())